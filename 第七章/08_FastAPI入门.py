# 从 fastapi 这个第三方包中，导入 FastAPI 类。
# FastAPI 可以帮助我们定义接口、处理请求和返回数据。
from fastapi import FastAPI


# 使用 FastAPI 类创建一个应用对象，并保存在变量 app 中。
# 和你之前写的 c = Dog(...) 一样，这里也是“使用类创建对象”。
# 后面通过 app 来登记接口，最后把 app 交给服务器运行。
app = FastAPI()


# @ 开头的这种语法叫“装饰器”。
# 这里的装饰器负责把下面的 root 函数登记为一个接口。
#
# app.get("/") 表示：
# 当应用收到访问 "/" 路径的 GET 请求时，
# 就调用下面的 root() 函数处理请求。
#
# GET 是一种 HTTP 请求方法，通常用于获取数据。
# 在浏览器地址栏输入网址并访问，通常发送的就是 GET 请求。
#
# "/" 是根路径。
# 这个接口的完整访问地址是：
# http://127.0.0.1:8000/
@app.get("/")
def root():
    # 这是处理首页请求的函数。
    # 程序启动时会登记这个函数对应的接口。
    # 收到匹配的请求后，FastAPI 才会调用这个函数。

    # 返回一个 Python 字典：
    # "message" 是键，"Hello World" 是对应的值。
    #
    # FastAPI 会把这个字典转换成 JSON 格式，
    # 再作为 HTTP 响应发送给浏览器。
    #
    # 浏览器最终会显示：
    # {"message": "Hello World"}
    #
    # 注意 return 和 print 的区别：
    # print(...)：把内容输出到 PyCharm 的运行窗口。
    # return ...：把结果交回给调用方；这里交给 FastAPI 处理。
    return {"message": "Hello World"}


# 登记另一个 GET 接口，路径是 "/users"。
#
# 当浏览器访问下面这个地址时：
# http://127.0.0.1:8000/users
# FastAPI 就会调用下面的 get_users() 函数。
#
# 访问路径由 "/users" 决定，
# get_users 是 Python 函数的名字，可以按需要命名。
@app.get("/users")
def get_users():
    # 返回一个列表，列表中的每个元素都是一个字典。
    # 每个字典保存一个用户的信息。
    #
    # 例如：
    # {"name": "Alice", "age": 30}
    # 表示用户的名字是 Alice，年龄是 30。
    #
    # 这些数据目前直接写在代码中。
    # 以后也可以让这个函数查询数据库，再返回查询结果。
    #
    # FastAPI 会把这个列表转换成 JSON 数据，
    # 发送给访问 /users 接口的浏览器或其他客户端。
    return [
        {"name": "Alice", "age": 30},
        {"name": "Bob", "age": 25},
        {"name": "Charlie", "age": 35}
    ]


# __name__ 是 Python 自动设置的一个特殊变量。
#
# 情况一：直接运行当前文件
# 例如，在 PyCharm 中右键当前文件，选择“运行”。
# 这时 __name__ 的值是 "__main__"，条件成立，
# 就会执行下面启动服务器的代码。
#
# 情况二：当前文件被其他 Python 文件作为模块导入
# 这时 __name__ 的值是模块名，条件不成立，
# 下面启动服务器的代码就不会自动执行。
if __name__ == "__main__":

    # 导入 Uvicorn。
    # Uvicorn 是用来运行 FastAPI 应用的 Web 服务器。
    # 它负责监听连接、接收请求，
    # 并把请求交给 FastAPI 应用处理。
    import uvicorn

    # 启动服务器。
    #
    # app：
    # 指定要运行哪个应用。
    # 就是上面通过 app = FastAPI() 创建的对象，
    # 里面已经登记了 "/" 和 "/users" 这两个接口。
    #
    # host="127.0.0.1"：
    # 指定监听本机回环地址。
    # 127.0.0.1 代表当前这台电脑，
    # 其他电脑不能通过这个地址访问你的服务。
    #
    # port=8000：
    # 指定监听 8000 端口。
    # 访问时要在地址后面带上 :8000。
    #
    # 执行到这里后，服务器会持续运行，等待并处理请求。
    # 运行窗口没有结束，是服务器正在工作的正常表现。
    # 停止这个程序后，服务也会停止。
    uvicorn.run(app, host="127.0.0.1", port=8000)